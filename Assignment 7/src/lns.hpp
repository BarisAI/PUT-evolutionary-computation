using Clock = std::chrono::steady_clock;
enum class Destroy { RandomNodes, OneSubpath, MultipleSubpaths };
inline const char* name(Destroy d) {
    switch(d) { case Destroy::RandomNodes: return "random_nodes";
                case Destroy::OneSubpath: return "one_subpath";
                case Destroy::MultipleSubpaths: return "multiple_subpaths"; }
    return "unknown";
}
struct Destroyed { Tour survivors; std::vector<int> removed; std::vector<unsigned char> removed_mask; int subpaths; };
struct Result {
    Tour best_tour;
    Cost best_objective=std::numeric_limits<Cost>::max();
    Cost initial_objective=0;
    int iterations=0, accepted=0, rejected=0, local_search_calls=0;
    double elapsed_ms=0;
    std::uint64_t delta_evaluations=0;
};
inline double elapsed(Clock::time_point start) {
    return std::chrono::duration<double,std::milli>(Clock::now()-start).count();
}
// A single pass of Fisher-Yates choosing k unique positions, without replacement.
inline std::vector<int> unique_positions(int n,int k,std::mt19937& rng) {
    if(k<0||k>n)throw std::invalid_argument("Invalid unique sample");
    std::vector<int> values(n);std::iota(values.begin(),values.end(),0);
    for(int i=0;i<k;++i){
        std::uniform_int_distribution<int> pick(i,n-1);
        std::swap(values[i],values[pick(rng)]);
    }
    values.resize(k);
    return values;
}
// Sample a random composition with lower bound min_part, preserving exact total.
inline std::vector<int> composition(int total,int parts,int min_part,std::mt19937& rng) {
    if(parts<1||total<parts*min_part)throw std::invalid_argument("Invalid composition");
    std::vector<int> out(parts,min_part);
    int remainder=total-parts*min_part;
    // A random stars-and-bars composition, generated by placing separator positions.
    if(parts>1 && remainder>0) {
        auto bars=unique_positions(remainder+parts-1,parts-1,rng);
        std::sort(bars.begin(),bars.end());
        int previous=-1;
        for(int i=0;i<parts-1;++i){out[i]+=bars[i]-previous-1;previous=bars[i];}
        out.back()+=remainder+parts-2-previous;
    } else out.back()+=remainder;
    return out;
}
inline Destroyed destroy(const Tour& original,Destroy method,int remove_count,std::mt19937& rng) {
    const int m=static_cast<int>(original.size());
    if(remove_count<1||remove_count>=m)throw std::invalid_argument("Destroy must leave at least one node");
    std::vector<unsigned char> remove(m,0);
    int sections=0;
    if(method==Destroy::RandomNodes) {
        for(int pos:unique_positions(m,remove_count,rng))remove[pos]=1;
    } else if(method==Destroy::OneSubpath) {
        const int start=std::uniform_int_distribution<int>(0,m-1)(rng);
        for(int j=0;j<remove_count;++j)remove[(start+j)%m]=1;
        sections=1;
    } else {
        // Exactly 3-5 nonadjacent circular subpaths. Random lengths and gaps
        // give an exact removal count without rejection loops or overlap.
        const int max_parts=std::min({5,remove_count/3,m-remove_count});
        const int min_parts=std::min(3,max_parts);
        if(min_parts<3)throw std::invalid_argument("Multi-subpath requires room for 3 separated segments");
        sections=std::uniform_int_distribution<int>(min_parts,max_parts)(rng);
        const auto lengths=composition(remove_count,sections,3,rng);
        const auto gaps=composition(m-remove_count,sections,1,rng);
        int cursor=std::uniform_int_distribution<int>(0,m-1)(rng);
        for(int j=0;j<sections;++j){
            for(int k=0;k<lengths[j];++k){remove[cursor]=1;cursor=(cursor+1)%m;}
            cursor=(cursor+gaps[j])%m;
        }
    }
    Destroyed out;
    out.removed_mask=remove;
    out.subpaths=sections;
    out.survivors.reserve(m-remove_count);out.removed.reserve(remove_count);
    for(int i=0;i<m;++i) {
        if(remove[i])out.removed.push_back(original[i]);
        else out.survivors.push_back(original[i]);
    }
    if(static_cast<int>(out.removed.size())!=remove_count)throw std::logic_error("Incorrect removal size");
    return out;
}
// Weighted two-regret: maximize (regret - minimum insertion cost)/2.
// This reproduces the original weight=0.5+0.5 criterion with exact integer ties.
inline Tour repair(const Problem& p,const Destroyed& partial,Basis basis,std::mt19937& rng) {
    Tour tour=partial.survivors;
    if(tour.empty())throw std::invalid_argument("Empty repair partial");
    if(basis==Basis::NearestAllPositions) {
        // Explicitly break the surviving cycle at a randomly selected edge.
        const int cut=std::uniform_int_distribution<int>(0,static_cast<int>(tour.size())-1)(rng);
        std::rotate(tour.begin(),tour.begin()+cut,tour.end());
    }
    std::vector<unsigned char> selected(p.size(),0);
    for(int u:tour){if(u<0||u>=p.size()||selected[u])throw std::invalid_argument("Invalid partial tour");selected[u]=1;}
    while(static_cast<int>(tour.size())<p.selected_count()){
        Cost best_score=std::numeric_limits<Cost>::min();
        Cost best_insertion=std::numeric_limits<Cost>::max();
        int chosen=-1,position=-1;
        for(int candidate=0;candidate<p.size();++candidate){
            if(selected[candidate])continue;
            const auto ins=insertion_choices(p,tour,candidate,basis);
            const Cost score=ins.regret-ins.best;
            // Same tie rules as Assignment 2; iteration over candidate IDs is increasing.
            if(score>best_score||(score==best_score&&ins.best<best_insertion)){
                best_score=score;best_insertion=ins.best;chosen=candidate;position=ins.position;
            }
        }
        if(chosen<0)throw std::logic_error("Repair found no candidate");
        tour.insert(tour.begin()+position,chosen);selected[chosen]=1;
    }
    return tour;
}
inline int removal_count(int selected_count,double fraction=0.30){
    if(fraction<=0||fraction>=1)throw std::invalid_argument("Removal fraction must be (0,1)");
    return std::clamp(static_cast<int>(std::llround(selected_count*fraction)),1,selected_count-1);
}
inline Result search(const Problem& p,Destroy destroy_method,bool local_after,
                     Basis repair_basis,std::uint32_t seed,double budget_ms) {
    if(budget_ms<=0)throw std::invalid_argument("Positive LNS budget required");
    std::mt19937 rng(seed);
    Result out;
    const auto start=Clock::now();
    const auto initial=local_search(p,random_solution(p,rng),LocalStrategy::Steepest,IntraMove::TwoOpt,rng);
    out.best_tour=initial.tour;out.best_objective=out.initial_objective=initial.objective;
    out.local_search_calls=1;out.delta_evaluations=initial.delta_checks;
    Tour current=std::move(initial.tour);
    const int nremove=removal_count(p.selected_count());
    // Stop checked BEFORE the next complete destroy/repair/(optional LS) iteration;
    // one last full iteration can exceed the budget slightly.
    while(elapsed(start)<budget_ms) {
        const Destroyed partial=destroy(current,destroy_method,nremove,rng);
        Tour candidate=repair(p,partial,repair_basis,rng);
        Cost score;
        if(local_after){
            auto improved=local_search(p,std::move(candidate),LocalStrategy::Steepest,IntraMove::TwoOpt,rng);
            out.delta_evaluations+=improved.delta_checks;
            ++out.local_search_calls;
            candidate=std::move(improved.tour);score=improved.objective;
        }else score=evaluate(p,candidate);
        ++out.iterations;
        // The task's pseudocode says f(y)>f(x), but our objective is MINIMIZED;
        // the correct non-worsening acceptance relation is f(y)<f(x).
        if(score<out.best_objective){
            out.best_objective=score;
            out.best_tour=candidate;
            current=std::move(candidate);
            ++out.accepted;
        }else ++out.rejected;
    }
    out.elapsed_ms=elapsed(start);
    return out;
}
